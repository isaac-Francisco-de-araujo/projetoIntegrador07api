-- Apenas responsabilidade; estados técnicos e diagnósticos permanecem nos históricos.
CREATE TABLE responsabilidades (
    origem VARCHAR(20) NOT NULL,
    referencia VARCHAR(36) NOT NULL,
    usuario_id BIGINT REFERENCES usuarios(id),
    versao BIGINT NOT NULL DEFAULT 0,
    atualizada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(origem,referencia)
);
CREATE INDEX ix_responsabilidades_usuario ON responsabilidades(usuario_id,atualizada_em);
CREATE TABLE eventos_responsabilidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem VARCHAR(20) NOT NULL,
    referencia VARCHAR(36) NOT NULL,
    anterior_usuario_id BIGINT REFERENCES usuarios(id),
    novo_usuario_id BIGINT REFERENCES usuarios(id),
    ator VARCHAR(100) NOT NULL,
    acao VARCHAR(20) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_eventos_responsabilidade ON eventos_responsabilidade(origem,referencia,id);
