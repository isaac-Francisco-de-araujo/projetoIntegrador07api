CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(100) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    papel VARCHAR(20) NOT NULL CHECK(papel IN ('CONSULTA','OPERADOR','ADMIN')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ator VARCHAR(100) NOT NULL,
    acao VARCHAR(10) NOT NULL,
    recurso VARCHAR(200) NOT NULL,
    referencia VARCHAR(255),
    status_http INTEGER NOT NULL,
    correlacao VARCHAR(36) NOT NULL,
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_auditoria_data ON auditoria(criada_em);
CREATE TABLE processamentos (
    id VARCHAR(36) PRIMARY KEY,
    anterior_id VARCHAR(36) REFERENCES processamentos(id),
    pacote VARCHAR(255) NOT NULL,
    sha256 VARCHAR(64),
    fase VARCHAR(30) NOT NULL,
    situacao VARCHAR(40) NOT NULL,
    ator VARCHAR(100) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    diagnostico TEXT NOT NULL,
    resultado TEXT
);
CREATE INDEX ix_processamentos_data ON processamentos(criado_em);
